"""Topological entropy metrics."""

import warnings

import networkx as nx
import numpy as np
from scipy.sparse.linalg import eigs

from symseq.utils.io import get_logger
from symseq.utils.linalg import spectral_radius
from symseq.utils.strtools import chunk_transitions

logger = get_logger(__name__)


class TopologicalEntropyWarning(UserWarning):
    """
    Warn that a topological entropy value is degenerate or not comparable to published values.

    Raised when TE is computed on an acyclic transition table, or (by
    `ArtificialGrammar.topological_entropy`) on a grammar whose table has no
    loop from the EOS state back to the start states. Filter it with
    ``warnings.filterwarnings("ignore", category=TopologicalEntropyWarning)``
    once the open-graph value is what you actually want.
    """


def warning_banner(title: str, lines: list[str]) -> str:
    """
    Format a multi-line warning message as a boxed banner.

    Parameters
    ----------
    title : str
        Headline of the banner.
    lines : list of str
        Body lines, one per bullet.

    Returns
    -------
    str
        The formatted banner.
    """
    rule = "!" * 78
    body = "\n".join(f"  - {line}" for line in lines)
    return f"\n{rule}\n  {title}\n{body}\n{rule}"


def topological_entropy(
    sequence: list | None = None,
    transitions: np.ndarray | None = None,
    max_lift: int = 15,
    method: str = "direct",
    verbose: bool = True,
    convergence_tol: float = 0.05,
) -> float | tuple:
    """
    Compute the topological entropy (TE) of a transition table or an observed sequence.

    Parameters
    ----------
    sequence : list, optional
        Sequence required if using the "lift" method.
    transitions : np.ndarray, optional
        Binary transition table required if using the "direct" method. For an
        artificial grammar, use `ArtificialGrammar.topological_entropy`, which
        builds this table and checks the loop-back closure (see Notes).
    max_lift : int, default=15
        Maximum lift order for the "lift" method.
    method : str, default="direct"
        Method to compute TE: "lift" or "direct".
    verbose : bool, default=True
        Show progress information.
    convergence_tol : float, default=0.05
        Lift method only. The lift order is considered converged when the
        absolute change in TE between successive lifts drops below this
        value (in nats).

    Returns
    -------
    float or tuple
        For "direct" method: topological entropy value in nats (0.0 by
        convention for an acyclic transition table, see Notes).
        For "lift" method: tuple of (lift, topological_entropy, TE_list).

    Raises
    ------
    TypeError
        If method-specific arguments have invalid types.
    ValueError
        If method-specific arguments are invalid, or if method is not "lift" or "direct".

    Warns
    -----
    TopologicalEntropyWarning
        "direct" method only: if the transition table is acyclic.

    Notes
    -----
    Topological entropy h_top(G) measures the exponential growth rate of
    distinct strings that can be generated by grammar G:

    h_top(G) = lim_{n->inf} (1/n) * ln(|L_n(G)|)

    For a known grammar with binary transition matrix T (direct method):
    h_top = ln(lambda_max(T)), where lambda_max is the spectral radius.

    The result is in nats (natural logarithm), consistent with the
    complexity targets used by the TE-based grammar synthesis. Divide by
    ln(2) to convert to bits.

    **Loop-back convention for artificial grammars.** A grammar that is
    entered at its start states and left at its terminal states is an *open*
    graph. In the artificial grammar learning (AGL) literature, TE is never
    computed on the open graph. It is computed on a *closed* graph in which
    every exit loops back to the start state(s), with the exit itself emitted
    as a delimiter symbol (Bollt & Jones, 2000, p. 165; Warren & Schroeder,
    2015, Sections 7.4.1 and 12.1; Vokey & Jamieson, 2020). TE is then the
    growth rate of concatenations of grammatical strings. In symseq, the EOS
    state plays the role of the delimiter, and the closure is the
    ``correct_terminal_sink=True`` option of the grammar's transition tables.
    Only closed values are comparable to published ones: for Reber (1967),
    the open table gives 0.382 and the closed table gives 0.602, the value
    reported by Schiff & Katan (2014) and Vokey & Jamieson (2020).

    **Acyclic tables.** An acyclic table generates a finite language, so
    |L_n(G)| = 0 for large n and, strictly, h_top = ln 0 = -inf (the table is
    nilpotent and its spectral radius is 0). This function returns 0.0 by
    convention ("no exponential growth") and emits a
    `TopologicalEntropyWarning`. An acyclic grammar still has a well-defined,
    positive TE under the loop-back convention above; compute it on the
    closed table.

    For observed sequences (lift method):
    Construct k-gram transition matrices M_k for increasing k until
    convergence. The sequence is treated as one long string, so if it
    concatenates grammatical strings (with delimiters), the estimate targets
    the closed-graph TE.

    References
    ----------
    Bollt, E. M., & Jones, M. A. (2000). The complexity of artificial
    grammars. Nonlinear Dynamics, Psychology, and Life Sciences, 4(2),
    153-168.

    Schiff, R., & Katan, P. (2014). Does complexity matter? Meta-analysis of
    learner performance in artificial grammar tasks. Frontiers in Psychology,
    5, 1084. doi:10.3389/fpsyg.2014.01084

    Warren, R., & Schroeder, P. J. (2015). Topological entropy measure of
    artificial grammar complexity for use in designing experiments on human
    performance in intelligence, surveillance, and reconnaissance (ISR)
    tasks. Technical Report ADA626837, Defense Technical Information Center.

    Vokey, J. R., & Jamieson, R. K. (2020). On the computation of the
    topological entropy of artificial grammars. The Quantitative Methods for
    Psychology, 16(4), 355-362. doi:10.20982/tqmp.16.4.p355
    """
    if verbose:
        logger.info(f"Computing topological entropy using the {method} method..")

    if method == "lift":
        if sequence is None:
            raise ValueError("The lift method requires a sequence")
        if len(sequence) <= 1000:
            logger.warning("Sequence is too short, entropy estimates may not be reliable.")

        TE = []
        lift, top_ent = 0, 0
        for lift in range(max_lift):
            M = chunk_transitions(sequence, lift + 1, verbose=False)
            evals_large, _ = eigs(M, 1, which="LM")
            max_eig = np.max(np.abs(evals_large))

            TE.append(np.log(max_eig))
            if verbose:
                logger.info(f"Lift: {lift + 1}; Entropy: {TE[-1]}")

            # Early stopping: if TE is NaN or negative, stop
            if np.isnan(TE[-1]) or TE[-1] < 0:
                if verbose:
                    logger.info(f"TE became {'NaN' if np.isnan(TE[-1]) else 'negative'}, stopping at lift {lift}")
                # Use the last valid TE value; `lift` is the index where it failed
                if len(TE) > 1:
                    top_ent = TE[-2]
                else:
                    top_ent = np.nan
                    lift = 0
                break

            if (len(TE) > 1) and (abs(TE[-1] - TE[-2]) < convergence_tol):
                top_ent = TE[-2]
                break
            else:
                top_ent = TE[-1]

            if np.isinf(top_ent):
                break

        return lift, top_ent, TE

    elif method == "direct":
        if not isinstance(transitions, np.ndarray):
            raise TypeError("Binary transition table is required for the direct method")
        if transitions.ndim != 2 or transitions.shape[0] != transitions.shape[1]:
            raise ValueError("The direct method requires a square 2D transition table")
        if not np.array_equal(transitions, transitions.astype(bool)):
            raise ValueError("The direct method requires a binary transition table")

        # Check acyclicity on the graph, not via spectral_radius == 0: the eigenvalues of a nilpotent
        # matrix are not always computed as exact zeros.
        if nx.is_directed_acyclic_graph(nx.from_numpy_array(transitions, create_using=nx.DiGraph)):
            warnings.warn(
                warning_banner(
                    "TOPOLOGICAL ENTROPY OF AN ACYCLIC TRANSITION TABLE",
                    [
                        "The table has no cycles, so it generates a finite language.",
                        "Strictly, TE = ln(0) = -inf; 0.0 is returned by convention.",
                        "The AGL literature computes TE on the closed graph, where exits loop back to the "
                        "start states (Bollt & Jones, 2000; Warren & Schroeder, 2015).",
                        "For an artificial grammar, use "
                        "ArtificialGrammar.topological_entropy(correct_terminal_sink=True).",
                    ],
                ),
                TopologicalEntropyWarning,
                stacklevel=2,
            )
            return 0.0
        return float(np.log(spectral_radius(transitions)))

    else:
        raise ValueError(f"Unknown method {method}. Use 'lift' or 'direct'.")
